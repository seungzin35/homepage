const INITIALS = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ';

/** "사과" → "ㅅㄱ" */
export function toChosung(word: string) {
  return [...word]
    .map((ch) => {
      const c = ch.charCodeAt(0) - 0xac00;
      return c >= 0 && c < 11172 ? INITIALS[Math.floor(c / 588)] : ch;
    })
    .join('');
}
